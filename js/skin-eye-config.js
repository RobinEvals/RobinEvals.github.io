/**
 * Get eye config for a dinosaur, with defaults applied.
 * @param {string} dinoName - Dinosaur key matching DINOSAUR_DATA
 * @returns {object} Eye configuration with all fields filled
 */
export function getEyeConfig(dinoName) {
	const cfg = EYE_CONFIG[dinoName];
	if (!cfg) return null;
	return {
		...cfg,
		irisScale: cfg.irisScale ?? DEFAULTS.irisScale,
		pupilScale: cfg.pupilScale ?? DEFAULTS.pupilScale,
		irisOutlineScale: cfg.irisOutlineScale ?? DEFAULTS.irisOutlineScale,
		irisBlur: cfg.irisBlur ?? DEFAULTS.irisBlur,
	};
}
